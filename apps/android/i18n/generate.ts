/**
 * Generates the Android string resources from the same catalogs the server and the web use:
 * shared messages (contracts) + web UI + Android-only keys. Run with `npm run android:strings`.
 *
 * Keys keep their meaning: `library.copies.one` → R.string.library_copies_one. Placeholders stay as
 * `{name}` and are filled in Kotlin by `Strings.format`, with the same semantics as the TypeScript side.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SHARED, type Dict, type Lang } from '@openlibrary/contracts';
import { en as webEn } from '../../web/src/i18n/en.js';
import { es as webEs } from '../../web/src/i18n/es.js';
import { en as androidEn } from './en.js';
import { es as androidEs } from './es.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const res = path.join(here, '../app/src/main/res');
const catalogs: Record<Lang, Dict> = {
  en: { ...SHARED.en, ...webEn, ...androidEn },
  es: { ...SHARED.es, ...webEs, ...androidEs },
};

const resName = (key: string) => key.replace(/[^A-Za-z0-9]+/g, '_');

/** Escapes a message for aapt: XML entities, quotes, apostrophes, leading @/? and line breaks. */
const escape = (s: string) =>
  s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n')
    .replace(/^([@?])/, '\\$1');

const names = new Map<string, string>();
for (const key of Object.keys(catalogs.en)) {
  const name = resName(key);
  const clash = names.get(name);
  if (clash && clash !== key) throw new Error(`"${key}" and "${clash}" map to the same resource ${name}`);
  names.set(name, key);
}
const missing = Object.keys(catalogs.en).filter((k) => !(k in catalogs.es));
if (missing.length) throw new Error(`Missing Spanish messages: ${missing.join(', ')}`);

for (const [lang, dir] of [
  ['en', 'values'],
  ['es', 'values-es'],
] as const) {
  const lines = [...names.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, key]) => {
      const value = catalogs[lang][key]!;
      const formatted = value.includes('%') ? ' formatted="false"' : '';
      return `    <string name="${name}"${formatted}>${escape(value)}</string>`;
    });
  const xml = [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- GENERATED by apps/android/i18n/generate.ts (npm run android:strings). Do not edit. -->',
    '<resources>',
    ...lines,
    '</resources>',
    '',
  ].join('\n');
  fs.mkdirSync(path.join(res, dir), { recursive: true });
  fs.writeFileSync(path.join(res, dir, 'strings.xml'), xml);
  console.log(`${dir}/strings.xml: ${lines.length} strings`);
}
